#!/usr/bin/env node
'use strict';

/**
 * Embed bookmarklet + CSS + helpers into panel-source.mjs so <Crank /> can
 * boot the UI from the app bundle (Retune pattern — no :3344 script fetch).
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'bookmarklet');

function read(name) {
  return fs.readFileSync(path.join(dir, name), 'utf8');
}

const bookmarklet = read('crank-bookmarklet.js');
const css = read('crank-ui.css');
const helpers = read('crank-ui-helpers.js');
const textSource = read('text-source.js');

const { normalizeChannel } = require('../lib/panel-channel');

const pkg = JSON.parse(
  fs.readFileSync(path.join(root, 'package.json'), 'utf8')
);
const panelChannel = normalizeChannel(process.env.CRANK_CHANNEL);
const panelVersionMeta = {
  version: String(pkg.version || '0.0.0'),
  build: new Date().toISOString(),
  channel: panelChannel
};
const panelVersionDir = path.join(root, 'panel');
fs.mkdirSync(panelVersionDir, { recursive: true });
fs.writeFileSync(
  path.join(panelVersionDir, 'panel-version.json'),
  `${JSON.stringify(panelVersionMeta, null, 2)}\n`
);

let gleanLogoDataUri = '';
try {
  gleanLogoDataUri =
    'data:image/png;base64,' +
    fs.readFileSync(path.join(dir, 'glean-logo.png')).toString('base64');
} catch {
  /* optional — companion /ui/glean-logo.png fallback */
}

const out = `/* Auto-generated by scripts/embed-panel.js — do not edit */
export const CRANK_PANEL_CHANNEL = ${JSON.stringify(panelChannel)};
export const CRANK_PANEL_VERSION = ${JSON.stringify(panelVersionMeta.version)};
export const CRANK_PANEL_BUILD = ${JSON.stringify(panelVersionMeta.build)};
export const CRANK_PANEL_JS = ${JSON.stringify(bookmarklet)};
export const CRANK_PANEL_CSS = ${JSON.stringify(css)};
export const CRANK_HELPERS_JS = ${JSON.stringify(helpers)};
export const CRANK_TEXT_SOURCE_JS = ${JSON.stringify(textSource)};
export const CRANK_GLEAN_LOGO_DATA_URI = ${JSON.stringify(gleanLogoDataUri)};
`;

const dest = path.join(root, 'panel-source.mjs');
fs.writeFileSync(dest, out);
console.log(
  '[crank] embedded panel-source.mjs',
  `${(Buffer.byteLength(out) / 1024).toFixed(1)} KB`
);
